import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const code = ts.transpileModule(fs.readFileSync('src/lib/services/tenant-client.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
const {tenantClient} = await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const calls=[];
const chain = new Proxy({}, {get(_t,k){return (...args)=>{calls.push([k,...args]);return chain;};}});
const raw={from(table){calls.push(['from',table]);return chain;},rpc(name,args){calls.push(['rpc',name,args]);return chain;}};
const client=tenantClient(raw,'school-a');
client.from('students').select('*');
assert.ok(calls.some(c=>c[0]==='eq'&&c[1]==='school_id'&&c[2]==='school-a'));
client.from('students').insert({display_name:'Fixture'});
assert.equal(calls.find(c=>c[0]==='insert')[1].school_id,'school-a');
assert.throws(()=>client.from('students').insert({school_id:'school-b'}));
assert.throws(()=>client.from('profiles'));
assert.throws(()=>client.rpc('provision_approved_school',{}));
client.rpc('collect_fee_payment_atomic',{p_school_id:'school-b'});
assert.equal(calls.find(c=>c[0]==='rpc')[2].p_school_id,'school-a');
client.from('school_configuration').select('*');
assert.ok(calls.some(c=>c[0]==='from'&&c[1]==='school_settings'));
assert.ok(calls.some(c=>c[0]==='throwOnError'));
console.log('PASS: 8 mocked tenant-client boundary assertions; not a database/RLS test.');
