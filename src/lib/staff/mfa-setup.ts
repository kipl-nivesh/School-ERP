import { isStaffUuid } from './contracts';

const SVG_LIMIT = 1_000_000;
const SVG_DATA_URI = /^data:image\/svg\+xml(?:;charset=utf-8|;utf-?8)?(;base64)?,/i;
const SVG_PROLOG = /^\s*(?:<\?xml\s+version=(?:"1\.0"|'1\.0')(?:\s+encoding=(?:"UTF-8"|'UTF-8'))?\s*\?>\s*)?(?:<!-- Generated by SVGo -->\s*)?/i;
const SVG_ROOT = /^<svg(?:\s+(?:width|height)="[1-9][0-9]{0,3}")*\s+xmlns="http:\/\/www\.w3\.org\/2000\/svg"(?:\s+xmlns:xlink="http:\/\/www\.w3\.org\/1999\/xlink")?\s*>([\s\S]*)<\/svg>$/;
const QR_RECTANGLE = /<rect\s+x="[0-9]{1,4}"\s+y="[0-9]{1,4}"\s+width="[1-9][0-9]{0,3}"\s+height="[1-9][0-9]{0,3}"\s+style="fill:(?:black|white);stroke:none"\s*\/>/g;
const CANONICAL_QR_PREFIX = 'data:image/svg+xml;base64,';

export function isTotpSetupSecret(value: unknown): value is string {
  return typeof value === 'string' && /^[A-Z2-7]{16,128}$/.test(value);
}

export function normalizeTotpQr(value: unknown): string | undefined {
  if (typeof value !== 'string' || value.length > SVG_LIMIT * 3) return;
  const header = SVG_DATA_URI.exec(value);
  let svg = value.slice(header?.[0].length ?? 0).trim();
  try {
    if (header?.[1]) {
      if (svg.length > Math.ceil(SVG_LIMIT / 3) * 4 || !/^[A-Za-z0-9+/]+={0,2}$/.test(svg)) return;
      const bytes = Buffer.from(svg, 'base64');
      if (bytes.toString('base64') !== svg) return;
      svg = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
    } else if (svg.startsWith('%')) {
      svg = decodeURIComponent(svg);
    }
  } catch {
    return;
  }
  if (svg.length > SVG_LIMIT) return;
  svg = svg.replace(SVG_PROLOG, '').trimEnd();
  const body = SVG_ROOT.exec(svg)?.[1];
  // GoTrue's QR contains only black and white rectangles. Reject all other markup
  // and attributes, including links, scripts, event handlers and arbitrary CSS.
  if (!body?.trim() || body.replace(QR_RECTANGLE, '').trim()) return;
  return CANONICAL_QR_PREFIX + Buffer.from(svg, 'utf8').toString('base64');
}

export function parseTotpSetup(data: { id: unknown; type: unknown; totp?: { qr_code?: unknown; secret?: unknown } }) {
  if (data.type !== 'totp' || !isStaffUuid(data.id) || !isTotpSetupSecret(data.totp?.secret)) return;
  const qrDataUri = normalizeTotpQr(data.totp.qr_code);
  if (!qrDataUri) return;
  return { factorId: data.id, qrDataUri, secret: data.totp.secret };
}
